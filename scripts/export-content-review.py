#!/usr/bin/env python3
"""Export every lesson, question and fault entry to docs/content-review.md.

The output is the pack given to a qualified marine engineer for sign-off.
It is generated from the bundled JSON, so re-run this after any content change:

    python3 scripts/export-content-review.py           # write the file
    python3 scripts/export-content-review.py --check   # fail if it is out of date

Standard library only.
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "DieselReady" / "Resources" / "Content"
OUTPUT = ROOT / "docs" / "content-review.md"
READER = ROOT / "DieselReady" / "Features" / "Learn" / "LessonReaderView.swift"
LETTERS = "ABCD"
DIFFICULTY = {1: "1 (easy)", 2: "2 (medium)", 3: "3 (hard)"}


def load():
    manifest = json.loads((CONTENT / "manifest.json").read_text(encoding="utf-8"))
    modules = [json.loads((CONTENT / "modules" / name).read_text(encoding="utf-8")) for name in manifest["modules"]]
    faults = None
    if manifest.get("faults"):
        faults = json.loads((CONTENT / manifest["faults"]).read_text(encoding="utf-8"))
    return modules, faults


def handbook_reminder():
    """The reminder the app adds to hands-on lessons, read from the Swift source."""
    match = re.search(r'static let text = "(.*?)"\n', READER.read_text(encoding="utf-8"))
    return match.group(1).replace("\\'", "'") if match else "(not found)"


def note(lines, text):
    lines.append(f"> **⚠️ Review note:** {text}")
    lines.append("")


def render(modules, faults):
    lessons_by_id = {}
    for module in modules:
        for index, lesson in enumerate(module["lessons"], start=1):
            lessons_by_id[lesson["id"]] = (module, index, lesson)

    all_questions = [q for m in modules for q in m["questions"]]
    all_notes = []  # (anchor, label, text)
    for module in modules:
        for lesson in module["lessons"]:
            if lesson.get("reviewNote"):
                all_notes.append((lesson["id"], f"{lesson['id']} lesson: {lesson['title']}", lesson["reviewNote"]))
            for q in module["questions"]:
                if q["lessonId"] == lesson["id"] and q.get("reviewNote"):
                    all_notes.append((q["id"], f"{q['id']} question", q["reviewNote"]))
    if faults:
        for s in faults["symptoms"]:
            if s.get("reviewNote"):
                all_notes.append((f"fault-{s['id']}", f"Fault finder: {s['title']}", s["reviewNote"]))

    out = []
    w = out.append
    w("# Diesel Ready: content review pack")
    w("")
    w("Generated by `scripts/export-content-review.py` from the bundled JSON. Do not edit by hand; "
      "edit the JSON and re-run the script.")
    w("")
    w("This pack contains every lesson, quiz question and Fault finder entry in the app, for review by a "
      "qualified marine engineer. Everything is currently marked **draft**. Items where the author was "
      "unsure, or where practice varies between engines, carry a **⚠️ Review note** saying what to check.")
    w("")
    w("The content deliberately gives no engine-specific figures (torque settings, pressures, clearances, "
      "oil grades or service intervals) and refers the reader to their engine handbook instead.")
    w("")
    w("## Summary")
    w("")
    w("| Module | Lessons | Questions | Difficulty 1 / 2 / 3 | Review notes | Reviewer sign-off |")
    w("|---|---|---|---|---|---|")
    for module in modules:
        diff = Counter(q["difficulty"] for q in module["questions"])
        notes = sum(1 for x in module["lessons"] + module["questions"] if x.get("reviewNote"))
        w(f"| {module['number']}. {module['title']} | {len(module['lessons'])} | {len(module['questions'])} | "
          f"{diff[1]} / {diff[2]} / {diff[3]} | {notes} | |")
    if faults:
        notes = sum(1 for s in faults["symptoms"] if s.get("reviewNote"))
        w(f"| Fault finder | {len(faults['symptoms'])} symptoms | | | {notes} | |")
    diff = Counter(q["difficulty"] for q in all_questions)
    w(f"| **Total** | **{sum(len(m['lessons']) for m in modules)}** | **{len(all_questions)}** | "
      f"**{diff[1]} / {diff[2]} / {diff[3]}** | **{len(all_notes)}** | |")
    w("")
    w("In the quiz, the four options are shuffled every time a question is shown. Here the correct "
      "answer is marked ✅.")
    w("")
    w("Every lesson marked hands-on ends with this reminder, added by the app:")
    w("")
    w(f"> {handbook_reminder()}")
    w("")

    w("## All review notes")
    w("")
    for anchor, label, text in all_notes:
        w(f"- [{label}](#{anchor}): {text}")
    w("")

    for module in modules:
        w(f"## Module {module['number']}: {module['title']}")
        w("")
        w(f"*{module['summary']}*")
        w("")
        for index, lesson in enumerate(module["lessons"], start=1):
            w(f'<a id="{lesson["id"]}"></a>')
            w("")
            hands = " · hands-on" if lesson["handsOn"] else ""
            w(f"### Lesson {module['number']}.{index}: {lesson['title']}")
            w("")
            w(f"`{lesson['id']}` · about {lesson['estimatedMinutes']} min{hands} · {lesson['reviewStatus']}")
            w("")
            if lesson.get("reviewNote"):
                note(out, lesson["reviewNote"])
            w(lesson["intro"])
            w("")
            diagram = lesson.get("diagram")
            if diagram:
                w(f"**Diagram ({diagram['kind']}).** {diagram['description']}")
                w("")
                for label in diagram["labels"]:
                    detail = f": {label['detail']}" if label.get("detail") else ""
                    w(f"- *{label['title']}*{detail}")
                if diagram.get("caption"):
                    w("")
                    w(f"Caption: {diagram['caption']}")
                w("")
            for number, step in enumerate(lesson["steps"], start=1):
                title = f"**{step['title']}.** " if step.get("title") else ""
                w(f"{number}. {title}{step['text']}")
            w("")
            if lesson.get("caution"):
                w(f"**Caution:** {lesson['caution']}")
                w("")
            if lesson["handsOn"]:
                w("*Ends with the handbook reminder.*")
                w("")

            questions = [q for q in module["questions"] if q["lessonId"] == lesson["id"]]
            w(f"#### Questions for lesson {module['number']}.{index} ({len(questions)})")
            w("")
            for q in questions:
                w(f'<a id="{q["id"]}"></a>')
                w("")
                w(f"**{q['id']}** · difficulty {DIFFICULTY[q['difficulty']]} · {q['reviewStatus']}")
                w("")
                if q.get("reviewNote"):
                    note(out, q["reviewNote"])
                w(f"{q['prompt']}")
                w("")
                for i, option in enumerate(q["options"]):
                    mark = " ✅" if i == q["correctIndex"] else ""
                    w(f"- {LETTERS[i]}. {option}{mark}")
                w("")
                w(f"*Explanation:* {q['explanation']}")
                w("")

    if faults:
        w("## Fault finder")
        w("")
        w(faults["intro"])
        w("")
        w(f"Every symptom ends with: *{faults['reminder']}*")
        w("")
        for s in faults["symptoms"]:
            w(f'<a id="fault-{s["id"]}"></a>')
            w("")
            w(f"### {s['title']}")
            w("")
            w(f"`{s['id']}` · {s['reviewStatus']}")
            w("")
            if s.get("reviewNote"):
                note(out, s["reviewNote"])
            w(s["summary"])
            w("")
            if s.get("stopFirst"):
                w(f"> **🛑 {s['stopFirst']['title']}.** {s['stopFirst']['text']}")
                w("")
            w("**Likely causes, most likely first**")
            w("")
            for i, cause in enumerate(s["causes"], start=1):
                w(f"{i}. **{cause['title']}.** {cause['detail']}")
            w("")
            w("**What to check first**")
            w("")
            for i, check in enumerate(s["checkFirst"], start=1):
                w(f"{i}. {check}")
            w("")
            w("**Related lessons**")
            w("")
            for lesson_id in s["lessonIds"]:
                module, index, lesson = lessons_by_id[lesson_id]
                w(f"- [{module['number']}.{index} {lesson['title']}](#{lesson_id})")
            w("")

    w("---")
    w("")
    w("Content © 2026 Meltemi Apps, licensed under CC BY-NC-SA 4.0. Unofficial; not affiliated with any "
      "training organisation, sailing association or engine manufacturer.")
    w("")
    return "\n".join(out)


def main():
    text = render(*load())
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print("docs/content-review.md is out of date. Run: python3 scripts/export-content-review.py")
            sys.exit(1)
        print("docs/content-review.md is up to date.")
        return
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
