#!/usr/bin/env python3
"""Export every lesson, question and fault entry for review.

Writes two files from the bundled JSON:

- docs/content-review.md: the pack given to a qualified marine engineer for sign-off.
- docs/quiz-review.csv: one row per question, with a severity and an empty
  sign-off column, for the question-level QA ledger.

Re-run this after any content change:

    python3 scripts/export-content-review.py           # write both files
    python3 scripts/export-content-review.py --check   # fail if either is out of date

Standard library only.
"""

import csv
import hashlib
import io
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "DieselReady" / "Resources" / "Content"
OUTPUT = ROOT / "docs" / "content-review.md"
CSV_OUTPUT = ROOT / "docs" / "quiz-review.csv"
READER = ROOT / "DieselReady" / "Features" / "Learn" / "LessonReaderView.swift"
LETTERS = "ABCD"
DIFFICULTY = {1: "1 (easy)", 2: "2 (medium)", 3: "3 (hard)"}

# Question ids the technical audit asked to be checked first (its section 7).
PRIORITY_IDS = {
    "m01-q004", "m01-q019", "m02-q010", "m02-q016", "m03-q004", "m03-q012", "m04-q020", "m05-q004",
    "m05-q006", "m06-q009", "m06-q012", "m06-q014", "m07-q010", "m08-q006", "m08-q012",
}
P0_FINDINGS = {"S01", "S02", "S03", "S04"}


def load():
    manifest = json.loads((CONTENT / "manifest.json").read_text(encoding="utf-8"))
    modules = [json.loads((CONTENT / "modules" / name).read_text(encoding="utf-8")) for name in manifest["modules"]]
    faults = None
    if manifest.get("faults"):
        faults = json.loads((CONTENT / manifest["faults"]).read_text(encoding="utf-8"))
    safety = None
    if manifest.get("safety"):
        safety = json.loads((CONTENT / manifest["safety"]).read_text(encoding="utf-8"))
    checks = None
    if manifest.get("checklists"):
        checks = json.loads((CONTENT / manifest["checklists"]).read_text(encoding="utf-8"))
    return modules, faults, safety, manifest.get("contentInfo"), checks


def audit_refs(text):
    """Finding and note ids mentioned in a review note, e.g. ['S12', 'note 24']."""
    if not text:
        return []
    refs = sorted(set(re.findall(r"\bS\d{2}\b", text)))
    refs += [f"note {n}" for n in sorted(set(re.findall(r"[Aa]udit note (\d+)", text)), key=int)]
    return refs


def severity(q):
    """P0 for safety-critical questions, P1 for audit priority or corrected items, P2 otherwise."""
    refs = set(audit_refs(q.get("reviewNote")))
    if q.get("safetyNoticeIds") or "safety-critical" in q.get("categories", []) or refs & P0_FINDINGS:
        return "P0"
    if q["id"] in PRIORITY_IDS or refs:
        return "P1"
    return "P2"


def handbook_reminder():
    """The reminder the app adds to hands-on lessons, read from the Swift source."""
    match = re.search(r'static let text = "(.*?)"\n', READER.read_text(encoding="utf-8"))
    return match.group(1).replace("\\'", "'") if match else "(not found)"


def note(lines, text):
    lines.append(f"> **⚠️ Review note:** {text}")
    lines.append("")


def notice_block(lines, safety, notice_id):
    notice = next(n for n in safety["notices"] if n["id"] == notice_id)
    icon = "🛑" if notice["level"] == "stop" else "⚠️"
    lines.append(f"> {icon} **{notice['title']}.** {notice['text']}")
    lines.append("")


def render(modules, faults, safety, info, checks=None):
    levels = {a["id"]: a["label"] for a in safety["actionLevels"]} if safety else {}
    tags = {t["id"]: t["label"] for t in safety["tags"]} if safety else {}
    lessons_by_id = {}
    for module in modules:
        for index, lesson in enumerate(module["lessons"], start=1):
            lessons_by_id[lesson["id"]] = (module, index, lesson)

    all_questions = [q for m in modules for q in m["questions"]]
    all_notes = []  # (anchor, label, text)
    for module in modules:
        for lesson in module["lessons"]:
            if lesson.get("reviewNote"):
                all_notes.append((lesson["id"], f"{lesson['id']} lesson: {lesson['title']}", lesson["reviewNote"]))
            for q in module["questions"]:
                if q["lessonId"] == lesson["id"] and q.get("reviewNote"):
                    all_notes.append((q["id"], f"{q['id']} question", q["reviewNote"]))
    if checks:
        for c in checks["checklists"]:
            if c.get("reviewNote"):
                all_notes.append((f"checklist-{c['id']}", f"Checklist: {c['title']}", c["reviewNote"]))
    if faults:
        for s in faults["symptoms"]:
            if s.get("reviewNote"):
                all_notes.append((f"fault-{s['id']}", f"Fault finder: {s['title']}", s["reviewNote"]))

    out = []
    w = out.append
    w("# Diesel Ready: content review pack")
    w("")
    w("Generated by `scripts/export-content-review.py` from the bundled JSON. Do not edit by hand; "
      "edit the JSON and re-run the script.")
    w("")
    w("This pack contains every lesson, quiz question, checklist and Fault finder entry in the app, for review by a "
      "qualified marine engineer. Everything is currently marked **draft**. Items where the author was "
      "unsure, or where practice varies between engines, carry a **⚠️ Review note** saying what to check.")
    w("")
    w("The content deliberately gives no engine-specific figures (torque settings, pressures, clearances, "
      "oil grades or service intervals) and refers the reader to their engine handbook instead.")
    w("")
    if info:
        w(f"**Content version:** {info['version']} ({info['status']}) · **Technical review:** {info['reviewDate']} · "
          f"**Engineer approval:** {info['engineerApproval']}")
        w("")
        w(f"**Changes in {info['changeLog'][0]['version']}:** {info['changeLog'][0]['summary']} "
          "See `docs/review-ledger.md` for each change by finding.")
        w("")
    if safety:
        w("Warnings are shown in the app **before** the steps they apply to. Each procedural step carries an "
          "action level: " + "; ".join(f"**{a['label']}** ({a['description'].rstrip('.')})" for a in safety["actionLevels"]) + ".")
        w("")
    w("## Summary")
    w("")
    w("| Module | Lessons | Questions | Difficulty 1 / 2 / 3 | Review notes | Reviewer sign-off |")
    w("|---|---|---|---|---|---|")
    for module in modules:
        diff = Counter(q["difficulty"] for q in module["questions"])
        notes = sum(1 for x in module["lessons"] + module["questions"] if x.get("reviewNote"))
        w(f"| {module['number']}. {module['title']} | {len(module['lessons'])} | {len(module['questions'])} | "
          f"{diff[1]} / {diff[2]} / {diff[3]} | {notes} | |")
    if checks:
        notes = sum(1 for c in checks["checklists"] if c.get("reviewNote"))
        items = sum(len(sec["items"]) for c in checks["checklists"] for sec in c["sections"])
        w(f"| Checklists | {len(checks['checklists'])} lists, {items} items | | | {notes} | |")
    if faults:
        notes = sum(1 for s in faults["symptoms"] if s.get("reviewNote"))
        w(f"| Fault finder | {len(faults['symptoms'])} symptoms | | | {notes} | |")
    diff = Counter(q["difficulty"] for q in all_questions)
    w(f"| **Total** | **{sum(len(m['lessons']) for m in modules)}** | **{len(all_questions)}** | "
      f"**{diff[1]} / {diff[2]} / {diff[3]}** | **{len(all_notes)}** | |")
    w("")
    w("In the quiz, the four options are shuffled every time a question is shown. Here the correct "
      "answer is marked ✅.")
    w("")
    w("Every lesson marked hands-on ends with this reminder, added by the app:")
    w("")
    w(f"> {handbook_reminder()}")
    w("")

    w("## All review notes")
    w("")
    for anchor, label, text in all_notes:
        w(f"- [{label}](#{anchor}): {text}")
    w("")

    for module in modules:
        w(f"## Module {module['number']}: {module['title']}")
        w("")
        w(f"*{module['summary']}*")
        w("")
        for index, lesson in enumerate(module["lessons"], start=1):
            w(f'<a id="{lesson["id"]}"></a>')
            w("")
            hands = " · hands-on" if lesson["handsOn"] else ""
            w(f"### Lesson {module['number']}.{index}: {lesson['title']}")
            w("")
            w(f"`{lesson['id']}` · about {lesson['estimatedMinutes']} min{hands} · {lesson['reviewStatus']}")
            w("")
            if lesson.get("reviewNote"):
                note(out, lesson["reviewNote"])
            w(lesson["intro"])
            w("")
            for notice_id in lesson.get("safetyNoticeIds", []):
                notice_block(out, safety, notice_id)
            if lesson.get("caution"):
                w(f"**Caution (shown before the steps):** {lesson['caution']}")
                w("")
            if lesson.get("appliesTo"):
                w("*Applies to:* " + ", ".join(tags[t] for t in lesson["appliesTo"]))
                w("")
            diagram = lesson.get("diagram")
            if diagram:
                w(f"**Diagram ({diagram['kind']}).** {diagram['description']}")
                w("")
                for label in diagram["labels"]:
                    detail = f": {label['detail']}" if label.get("detail") else ""
                    w(f"- *{label['title']}*{detail}")
                if diagram.get("caption"):
                    w("")
                    w(f"Caption: {diagram['caption']}")
                w("")
            for number, step in enumerate(lesson["steps"], start=1):
                title = f"**{step['title']}.** " if step.get("title") else ""
                action = f"`{levels[step['action']]}` " if step.get("action") else ""
                w(f"{number}. {action}{title}{step['text']}")
            w("")
            if lesson["handsOn"]:
                w("*Ends with the handbook reminder.*")
                w("")
            if lesson.get("checklistIds"):
                w("*Links to the checklists:* " + ", ".join(f"[{c}](#checklist-{c})" for c in lesson["checklistIds"]))
                w("")

            questions = [q for q in module["questions"] if q["lessonId"] == lesson["id"]]
            w(f"#### Questions for lesson {module['number']}.{index} ({len(questions)})")
            w("")
            for q in questions:
                w(f'<a id="{q["id"]}"></a>')
                w("")
                cats = "".join(f" · {c}" for c in q.get("categories", []))
                w(f"**{q['id']}** · difficulty {DIFFICULTY[q['difficulty']]}{cats} · {q['reviewStatus']}")
                w("")
                if q.get("reviewNote"):
                    note(out, q["reviewNote"])
                w(f"{q['prompt']}")
                w("")
                for i, option in enumerate(q["options"]):
                    mark = " ✅" if i == q["correctIndex"] else ""
                    w(f"- {LETTERS[i]}. {option}{mark}")
                w("")
                w(f"*Explanation:* {q['explanation']}")
                w("")
                if q.get("safetyNoticeIds"):
                    titles = [next(n for n in safety["notices"] if n["id"] == i) for i in q["safetyNoticeIds"]]
                    w("*Feedback also shows:* " + "; ".join(f"{n['title']} (`{n['id']}`)" for n in titles))
                    w("")

    if checks:
        render_checklists(out, checks, safety, levels, lessons_by_id, faults)

    if faults:
        w("## Fault finder")
        w("")
        w(faults["intro"])
        w("")
        w(f"Every symptom ends with: *{faults['reminder']}*")
        w("")
        w("### Stop cards (shown first, before the symptoms)")
        w("")
        for card in faults["stopCards"]:
            w(f"**🛑 {card['title']}** (`{card['id']}`)")
            w("")
            w(f"- **STOP:** {card['stop']}")
            w(f"- **DO NOT RESTART:** {card['doNotRestart']}")
            w(f"- **GET ASSISTANCE:** {card['getAssistance']}")
            w("")
        for s in faults["symptoms"]:
            w(f'<a id="fault-{s["id"]}"></a>')
            w("")
            w(f"### {s['title']}")
            w("")
            w(f"`{s['id']}` · {s['reviewStatus']}")
            w("")
            if s.get("reviewNote"):
                note(out, s["reviewNote"])
            for notice_id in s.get("safetyNoticeIds", []):
                notice_block(out, safety, notice_id)
            if s.get("stopCardIds"):
                w("Then the stop card" + ("s" if len(s["stopCardIds"]) > 1 else "") + ": "
                  + ", ".join(f"`{c}`" for c in s["stopCardIds"]))
                w("")
            w(s["summary"])
            w("")
            w("**Possible causes (not ranked)**")
            w("")
            for cause in s["possibleCauses"]:
                w(f"- **{cause['title']}.** {cause['detail']}")
            w("")
            w("**What to check first**")
            w("")
            for i, check in enumerate(s["checkFirst"], start=1):
                w(f"{i}. {check}")
            w("")
            w("**Related lessons**")
            w("")
            for lesson_id in s["lessonIds"]:
                module, index, lesson = lessons_by_id[lesson_id]
                w(f"- [{module['number']}.{index} {lesson['title']}](#{lesson_id})")
            w("")

    w("---")
    w("")
    w("Content © 2026 Meltemi Apps, licensed under CC BY-NC-SA 4.0. Unofficial; not affiliated with any "
      "training organisation, sailing association or engine manufacturer.")
    w("")
    return "\n".join(out)


def render_checklists(out, checks, safety, levels, lessons_by_id, faults):
    w = out.append
    aid = checks["mnemonic"]
    symptoms = {s["id"]: s["title"] for s in (faults or {}).get("symptoms", [])}
    w("## Checklists")
    w("")
    w(f"The Checks tab. {aid['summary']}")
    w("")
    w("Letters: " + ", ".join(f"**{x['letter']}** {x['word']}" for x in aid["letters"]))
    w("")
    w(f"Every checklist ends with: *{checks['reminder']}*")
    w("")
    w("Ticks are kept in memory for the session only; nothing is stored or sent.")
    w("")
    for c in checks["checklists"]:
        w(f'<a id="checklist-{c["id"]}"></a>')
        w("")
        w(f"### {c['title']}: {c['subtitle'].lower()}")
        w("")
        module, index, lesson = lessons_by_id[c["lessonId"]]
        w(f"`{c['id']}` · {c['reviewStatus']} · lesson [{module['number']}.{index} {lesson['title']}](#{c['lessonId']})")
        w("")
        if c.get("reviewNote"):
            note(out, c["reviewNote"])
        if c.get("banner"):
            w(f"> **Banner (shown first):** {c['banner']}")
            w("")
        w(c["intro"])
        w("")
        for sec in c["sections"]:
            letter = f"{sec['letter']}: " if sec.get("letter") else ""
            w(f"**{letter}{sec['title']}**")
            w("")
            for item in sec["items"]:
                m, i, l = lessons_by_id[item["lessonId"]]
                extra = f" · lesson {m['number']}.{i}"
                if item.get("symptomId"):
                    extra += f" · Fault finder: {symptoms.get(item['symptomId'], item['symptomId'])}"
                w(f"- [ ] `{levels[item['action']]}` **{item['title']}.** {item['detail']} *({item['id']}{extra})*")
                for notice_id in item.get("safetyNoticeIds", []):
                    n = next(x for x in safety["notices"] if x["id"] == notice_id)
                    w(f"  - *Shows the shared notice:* {n['title']} (`{n['id']}`)")
            w("")


def render_csv(modules):
    """One row per question. Options are shuffled with a fixed seed per question,
    so the key is not always option A and a second reviewer can answer the
    bank blind by hiding the key column."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["id", "module", "lesson", "difficulty", "stem", "option_a", "option_b", "option_c", "option_d",
                     "key", "explanation", "safety_notices", "safety_critical", "scenario", "unsafe_distractor",
                     "severity", "audit_refs", "sign_off"])
    for module in modules:
        for q in module["questions"]:
            order = list(range(4))
            random.Random(int(hashlib.sha256(q["id"].encode()).hexdigest(), 16)).shuffle(order)
            options = [q["options"][i] for i in order]
            key = LETTERS[order.index(q["correctIndex"])]
            writer.writerow([q["id"], f"{module['number']}. {module['title']}", q["lessonId"], q["difficulty"],
                             q["prompt"], *options, key, q["explanation"],
                             " ".join(q.get("safetyNoticeIds", [])),
                             *("yes" if c in q.get("categories", []) else "" for c in ("safety-critical", "scenario", "unsafe-distractor")),
                             severity(q),
                             " ".join(audit_refs(q.get("reviewNote"))), ""])
    return buffer.getvalue()


def main():
    data = load()
    outputs = {OUTPUT: render(*data), CSV_OUTPUT: render_csv(data[0])}
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date. Run: python3 scripts/export-content-review.py")
        if stale:
            sys.exit(1)
        print("docs/content-review.md and docs/quiz-review.csv are up to date.")
        return
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
